/// An observed change to a DNS resource.
///
/// Variants are `#[non_exhaustive]` so new event kinds can be added without a
/// breaking change. Match with a wildcard arm.
///
/// Watch callbacks must only publish or coalesce events; expensive or
/// mutating logic must never run inside a callback. Events caused by our own
/// mutations are suppressed from the user callback path (under
/// [`ConflictPolicy::Enforce`](crate::ConflictPolicy) the reconciler still
/// observes them via read-back before suppression applies).
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum DnsEvent {
    /// The resource's DNS configuration changed.
    ResourceChanged {
        /// The resource that changed.
        resource: ResourceId,
    },
    /// The resource disappeared (e.g. an interface was removed).
    ResourceRemoved {
        /// The resource that disappeared.
        resource: ResourceId,
    },
}

impl DnsEvent {
    pub(crate) fn resource(&self) -> &ResourceId {
        match self {
            DnsEvent::ResourceChanged { resource } => resource,
            DnsEvent::ResourceRemoved { resource } => resource,
        }
    }
}

/// Callback invoked by a backend's event thread.
///
/// Must be `Send + Sync` because it runs on a native watcher thread. Keep it
/// short: publish the event and return. Never call [`DnsManager::apply`](crate::DnsManager::apply),
/// [`Lease::restore`](crate::Lease::restore), or other mutating APIs from
/// inside the callback; doing so risks deadlock with the coalescer and
/// reconciler threads.
pub type WatchCallback = Arc<dyn Fn(&DnsEvent) + Send + Sync>;

/// A live watch. Cancels the underlying native notification when dropped or
/// explicitly stopped.
///
/// `stop` consumes the handle; dropping has the same effect. Stopping is
/// idempotent and never fails. Stopping a public watch never disables
/// [`ConflictPolicy::Enforce`](crate::ConflictPolicy): Enforce keeps its own
/// internal observation alive while leases are active.
///
/// ```no_run
/// # use osdns::DnsManager;
/// # use std::sync::Arc;
/// # fn main() -> osdns::Result<()> {
/// # let manager = DnsManager::builder().owner("io.example.agent").build()?;
/// let watch = manager.watch(Arc::new(|event| println!("{event:?}")))?;
/// // ... observe events ...
/// watch.stop();
/// # Ok(())
/// # }
/// ```
pub struct WatchHandle {
    flag: Arc<AtomicBool>,
    pub(crate) delivery: Option<Arc<AtomicBool>>,
    cancel: Mutex<Option<Box<dyn FnOnce() + Send>>>,
}

impl WatchHandle {
    #[allow(dead_code)]
    pub(crate) fn new(flag: Arc<AtomicBool>, cancel: impl FnOnce() + Send + 'static) -> Self {
        Self {
            flag,
            delivery: None,
            cancel: Mutex::new(Some(Box::new(cancel))),
        }
    }

    /// Whether native observation and callback delivery remain operational.
    /// Worker termination deactivates this state while the handle remains owned.
    pub fn is_active(&self) -> bool {
        !self.flag.load(Ordering::Acquire)
            && !self
                .delivery
                .as_ref()
                .is_some_and(|flag| flag.load(Ordering::Acquire))
    }

    pub(crate) fn flag(&self) -> Arc<AtomicBool> {
        Arc::clone(&self.flag)
    }

    /// Stops the watch and releases the underlying native notification.
    ///
    /// Consumes the handle; equivalent to dropping it. After `stop` no
    /// further callbacks will be delivered for this watch.
    pub fn stop(mut self) {
        self.deactivate();
    }

    fn deactivate(&mut self) {
        self.flag.store(true, Ordering::Release);
        if let Some(cancel) = self.cancel.lock().take() {
            cancel();
        }
    }
}

pub(crate) struct WatchWorker(pub(crate) Arc<AtomicBool>);

impl Drop for WatchWorker {
    fn drop(&mut self) {
        self.0.store(true, Ordering::Release);
    }
}

impl Drop for WatchHandle {
    fn drop(&mut self) {
        self.deactivate();
    }
}

impl fmt::Debug for WatchHandle {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("WatchHandle")
            .field("active", &self.is_active())
            .finish()
    }
}

/// Tracks the resources the transaction engine has recently mutated, so
/// watcher events generated by our own mutations are suppressed instead of
/// being reported as external changes.
#[derive(Debug, Default)]
pub(crate) struct SuppressionRegistry {
    entries: Mutex<HashMap<ResourceId, (Instant, crate::platform::PlatformSnapshot)>>,
}

impl SuppressionRegistry {
    const WINDOW: Duration = Duration::from_millis(500);

    pub(crate) fn new() -> Self {
        Self::default()
    }

    pub(crate) fn record(&self, snapshot: &crate::platform::PlatformSnapshot) {
        let mut entries = self.entries.lock();
        Self::prune(&mut entries);
        entries.insert(
            snapshot.resource.clone(),
            (Instant::now(), snapshot.clone()),
        );
    }

    pub(crate) fn snapshot(
        &self,
        resource: &ResourceId,
    ) -> Option<crate::platform::PlatformSnapshot> {
        let mut entries = self.entries.lock();
        Self::prune(&mut entries);
        entries.get(resource).map(|(_, snapshot)| snapshot.clone())
    }

    fn prune(entries: &mut HashMap<ResourceId, (Instant, crate::platform::PlatformSnapshot)>) {
        let now = Instant::now();
        entries.retain(|_, (suppressed_at, _)| now.duration_since(*suppressed_at) < Self::WINDOW);
    }
}

/// Wraps a callback so bursts of events for the same resource coalesce into
/// a single delivery.
///
/// The returned callback replaces the latest pending event for its resource
/// and signals a capacity-one wake channel with `try_send`. A dedicated
/// thread flushes the latest events at the end of each bounded `window`.
pub(crate) fn spawn_coalescer(
    kind: BackendKind,
    callback: WatchCallback,
    window: Duration,
) -> Result<Coalescer> {
    let pending = Arc::new(Mutex::new(HashMap::<ResourceId, DnsEvent>::new()));
    let worker_pending = Arc::clone(&pending);
    let (wake, rx) = mpsc::sync_channel::<()>(1);
    let flag = Arc::new(AtomicBool::new(false));
    let worker_flag = Arc::clone(&flag);
    let worker = thread::Builder::new()
        .name("osdns-watch-coalescer".to_string())
        .spawn(move || {
            let _lifetime = WatchWorker(Arc::clone(&worker_flag));
            while rx.recv().is_ok() {
                if worker_flag.load(Ordering::Acquire) {
                    break;
                }
                let deadline = Instant::now() + window;
                loop {
                    let remaining = deadline.saturating_duration_since(Instant::now());
                    if remaining.is_zero() {
                        break;
                    }
                    match rx.recv_timeout(remaining) {
                        Ok(()) if worker_flag.load(Ordering::Acquire) => return,
                        Ok(()) => {}
                        Err(mpsc::RecvTimeoutError::Timeout) => break,
                        Err(mpsc::RecvTimeoutError::Disconnected) => {
                            flush(&callback, &worker_pending, &worker_flag);
                            return;
                        }
                    }
                }
                flush(&callback, &worker_pending, &worker_flag);
            }
        })
        .map_err(|e| Error::Platform {
            backend: kind,
            message: format!("cannot spawn coalescer thread: {e}"),
        })?;
    let callback_flag = Arc::clone(&flag);
    let callback_wake = wake.clone();
    let sender: WatchCallback = Arc::new(move |event| {
        if callback_flag.load(Ordering::Acquire) {
            return;
        }
        pending
            .lock()
            .insert(event.resource().clone(), event.clone());
        let _ = callback_wake.try_send(());
    });
    Ok(Coalescer {
        flag,
        wake,
        sender: Some(sender),
        worker: Some(worker),
    })
}

pub(crate) struct Coalescer {
    pub(crate) flag: Arc<AtomicBool>,
    wake: mpsc::SyncSender<()>,
    sender: Option<WatchCallback>,
    worker: Option<thread::JoinHandle<()>>,
}

impl Coalescer {
    pub(crate) fn callback(&self) -> WatchCallback {
        self.sender.as_ref().expect("active coalescer").clone()
    }

    pub(crate) fn stop(mut self) {
        self.deactivate();
    }

    fn deactivate(&mut self) {
        self.flag.store(true, Ordering::Release);
        let _ = self.wake.try_send(());
        self.sender.take();
        if let Some(worker) = self.worker.take()
            && worker.thread().id() != thread::current().id()
        {
            let _ = worker.join();
        }
    }
}

impl Drop for Coalescer {
    fn drop(&mut self) {
        self.deactivate();
    }
}

fn flush(
    callback: &WatchCallback,
    shared: &Mutex<HashMap<ResourceId, DnsEvent>>,
    flag: &AtomicBool,
) {
    let pending = {
        let mut shared = shared.lock();
        std::mem::take(&mut *shared)
    };
    for event in pending.values() {
        if flag.load(Ordering::Acquire) {
            break;
        }
        callback(event);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn coalescer_delivers_the_last_event_from_a_burst() {
        let (sent, received) = mpsc::channel();
        let (release, blocked) = mpsc::channel();
        let blocked = Mutex::new(blocked);
        let coalescer = spawn_coalescer(
            BackendKind::Fake,
            Arc::new(move |event| {
                sent.send(event.clone()).unwrap();
                blocked.lock().recv_timeout(Duration::from_secs(2)).unwrap();
            }),
            Duration::from_millis(5),
        )
        .unwrap();
        let callback = coalescer.callback();
        let resource = ResourceId::new("fake:watch-state").unwrap();
        let changed = DnsEvent::ResourceChanged {
            resource: resource.clone(),
        };
        callback(&changed);
        assert_eq!(
            received.recv_timeout(Duration::from_secs(2)).unwrap(),
            changed
        );
        for _ in 0..300 {
            callback(&DnsEvent::ResourceRemoved {
                resource: resource.clone(),
            });
        }
        callback(&changed);
        release.send(()).unwrap();
        assert_eq!(
            received.recv_timeout(Duration::from_secs(2)).unwrap(),
            changed
        );
        release.send(()).unwrap();
        assert!(received.recv_timeout(Duration::from_millis(50)).is_err());
        coalescer.stop();
    }
    #[test]
    fn coalescer_stop_does_not_depend_on_sender_release() {
        let coalescer = spawn_coalescer(
            BackendKind::Fake,
            Arc::new(|_| {}),
            Duration::from_millis(5),
        )
        .unwrap();
        let retained = coalescer.callback();
        coalescer.stop();
        drop(retained);
    }
}
